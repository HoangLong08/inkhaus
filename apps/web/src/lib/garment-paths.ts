/**
 * The blank shapes, as raw SVG path data on a 600x700 viewBox.
 *
 * Pure data, deliberately not a client component: `Garment.tsx` renders these,
 * but the catalog invariant test also has to assert that every `GarmentType`
 * has an entry here, and a test cannot reach a const that lives inside a
 * `"use client"` module.
 *
 * Coordinates are shared with `Product.printArea`, so moving a body path means
 * re-checking that blank's print box.
 */
import type { GarmentType } from "@/lib/catalog";

/** mix a hex colour toward black (t<0) or white (t>0) */
export function shade(hex: string, t: number) {
  const n = parseInt(hex.replace("#", ""), 16);
  const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) =>
    Math.round(t < 0 ? v * (1 + t) : v + (255 - v) * t)
  );
  return `rgb(${c[0]},${c[1]},${c[2]})`;
}

