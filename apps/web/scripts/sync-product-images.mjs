/**
 * Regenerates packages/shared/src/product-images.ts from whatever is sitting in
 * apps/web/public/products/.
 *
 * Touches the network never. That is the point: however the photographs got
 * onto disk — the Etsy crawler, a supplier zip, someone's phone, a browser's
 * "save image as" — this step is the same, so the catalog can always be rebuilt
 * offline and on any machine.
 *
 * Filenames carry the metadata:
 *
 *   public/products/<slug>/<nn>-<colorkey|any>[@2x].<ext>
 *   public/products/heavyweight-tee/01-black.jpg
 *   public/products/heavyweight-tee/01-black@2x.jpg    <- lightbox master
 *   public/products/heavyweight-tee/03-any.jpg         <- shown for every colour
 *
 *   node scripts/sync-product-images.mjs           # write the file
 *   node scripts/sync-product-images.mjs --check   # exit 1 if it is out of date
 *
 * Requires the shared package to be built first:  npm run build:shared
 */
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

import { imageSize } from "./lib/image-size.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PRODUCTS_DIR = path.join(root, "public", "products");
const OUT = path.resolve(root, "..", "..", "packages", "shared", "src", "product-images.ts");

const CHECK = process.argv.includes("--check");

/** <nn>-<colorkey|any>[@2x].<ext> */
const NAME = /^(\d{2})-([a-z]+)(@2x)?\.(jpe?g|png|webp)$/i;

const require = createRequire(import.meta.url);
let shared;
try {
  shared = require("@inkhaus/shared");
} catch {
  console.error("Build the shared package first:  npm run build:shared");
  process.exit(1);
}
const { PRODUCTS, COLORS } = shared;
const bySlug = new Map(PRODUCTS.map((p) => [p.slug, p]));

const problems = [];

async function collect() {
  if (!existsSync(PRODUCTS_DIR)) return {};

  const out = {};
  const dirs = (await readdir(PRODUCTS_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
    .map((d) => d.name)
    .sort();

  for (const slug of dirs) {
    const product = bySlug.get(slug);
    if (!product) {
      problems.push(`public/products/${slug}/ does not match any product slug`);
      continue;
    }

    const files = (await readdir(path.join(PRODUCTS_DIR, slug))).sort();
    // a 2x master is an attribute of its base image, not an image of its own
    const masters = new Set(files.filter((f) => NAME.exec(f)?.[3]));
    const entries = [];

    for (const file of files) {
      const m = NAME.exec(file);
      if (!m) {
        problems.push(`${slug}/${file} does not match <nn>-<colorkey|any>[@2x].<ext>`);
        continue;
      }
      if (m[3]) continue; // handled via its base

      const key = m[2];
      if (key !== "any" && !COLORS[key]) {
        problems.push(`${slug}/${file} names colour "${key}", which is not in COLORS`);
        continue;
      }
      if (key !== "any" && !product.colors.some((c) => c.hex === COLORS[key].hex)) {
        problems.push(`${slug}/${file} names colour "${key}", which ${slug} does not stock`);
        continue;
      }

      const abs = path.join(PRODUCTS_DIR, slug, file);
      const dim = imageSize(await readFile(abs));
      if (!dim) {
        problems.push(`${slug}/${file} is not a readable jpg/png/webp`);
        continue;
      }

      const twoX = file.replace(/\.(\w+)$/, "@2x.$1");
      entries.push({
        src: `/products/${slug}/${file}`,
        alt: key === "any" ? product.name : `${product.name} — ${COLORS[key].name}`,
        w: dim.w,
        h: dim.h,
        ...(key === "any" ? {} : { color: key }),
        ...(masters.has(twoX) ? { src2x: `/products/${slug}/${twoX}` } : {}),
      });
    }

    if (entries.length) out[slug] = entries;
  }
  return out;
}

/** deterministic, so a re-run with no new files produces no diff */
function render(map) {
  const slugs = Object.keys(map).sort();
  const body = slugs
    .map((slug) => {
      const rows = map[slug]
        .map((i) => `    ${JSON.stringify(i)},`)
        .join("\n");
      return `  ${JSON.stringify(slug)}: [\n${rows}\n  ],`;
    })
    .join("\n");

  return `// GENERATED by apps/web/scripts/sync-product-images.mjs — do not edit by hand.
// Regenerate with:  npm run images:sync -w @inkhaus/web
//
// Every entry is a file committed under apps/web/public/products/<slug>/.
// An empty map is a valid state: the storefront falls back to the SVG blanks.
import type { ProductImage } from "./catalog";

export const PRODUCT_IMAGES: Record<string, ProductImage[]> = {${
    slugs.length ? `\n${body}\n` : ""
  }};
`;
}

const map = await collect();
const next = render(map);
const current = existsSync(OUT) ? await readFile(OUT, "utf8") : "";

for (const p of problems) console.error(`  ! ${p}`);

const count = Object.values(map).reduce((n, v) => n + v.length, 0);
const shown = `${count} image${count === 1 ? "" : "s"} across ${Object.keys(map).length} product(s)`;

if (CHECK) {
  if (next !== current) {
    console.error(`product-images.ts is out of date (${shown}). Run: npm run images:sync -w @inkhaus/web`);
    process.exit(1);
  }
  console.log(`product-images.ts is up to date — ${shown}`);
  process.exit(problems.length ? 1 : 0);
}

if (next === current) {
  console.log(`no change — ${shown}`);
} else {
  await writeFile(OUT, next);
  console.log(`wrote ${path.relative(root, OUT)} — ${shown}`);
  console.log("Now rebuild the shared package:  npm run build:shared");
}

// a misnamed file is a silent missing photo, so make it fail the run
if (problems.length) process.exit(1);
